def test_archives_old_goals_stuck_on_approval(monkeypatch):
    """A goal whose only-remaining subtask is the human approval
    step AND has been waiting longer than STALE_DAYS gets marked
    `failed` with a clear reason — clears the backlog."""
    from backend.autonomic.levers.goal_executor import (
        FIRE_GOAL_EXECUTOR, STALE_DAYS,
    )
    from backend import goals as g_mod
    from backend import self_modifier as sm

    old_goal = _make_improvement_goal(age_days=STALE_DAYS + 5)
    old_goal.complete_subtask(0, "x")
    old_goal.complete_subtask(1, "x")
    # Only "Approve or reject explicitly" remains pending — but
    # 19 days have passed.
    monkeypatch.setattr(g_mod.GOALS, "_goals", [old_goal])
    monkeypatch.setattr(g_mod.GOALS, "_save", lambda: None)
    monkeypatch.setattr(sm.SELF_MODIFIER, "_proposals", [])
    monkeypatch.setattr(sm.SELF_MODIFIER, "analyze_module",
                        lambda mn: [])

    lever = FIRE_GOAL_EXECUTOR()
    lever.run({}, {})

    assert old_goal.status == "failed"
    assert "stale" in (old_goal.progress_notes[-1] if old_goal.progress_notes
                       else "").lower() or old_goal.completed is not None


def test_handles_unparseable_subtask_descriptions(monkeypatch):
    """A goal with subtask descriptions that don't match the known
    patterns (free-form text from user-added goals) is skipped
    cleanly — no exception, no spurious action."""
    from backend.autonomic.levers.goal_executor import FIRE_GOAL_EXECUTOR
    from backend import goals as g_mod
    from backend.goals import Goal

    custom_goal = Goal(
        description="user typed something else",
        goal_type="improvement",
        subtasks=[
            {"description": "do thing X", "status": "pending", "result": ""},
        ],
    )
    monkeypatch.setattr(g_mod.GOALS, "_goals", [custom_goal])
    monkeypatch.setattr(g_mod.GOALS, "_save", lambda: None)

    lever = FIRE_GOAL_EXECUTOR()
    report = lever.run({}, {})
    # Status doesn't matter — the goal just isn't touched.
    assert custom_goal.subtasks[0]["status"] == "pending"
