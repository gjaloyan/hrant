"""FIRE_GOAL_EXECUTOR — drive improvement-goals through their
subtasks programmatically.

Audit 2026-05-27 prod state: 18 active goals, all generated by
meta_learner, all stuck. Subtasks of the form
  - "Run SELF_MODIFIER.analyze_module('verifier')"
  - "Review the resulting proposal in the WebUI"
  - "Approve or reject explicitly"

The first two CAN be done by the autonomic loop. The third stays
human. The lever executes (1) and (2), marks them done, leaves
(3) for the operator. After STALE_DAYS waiting on (3), archives
the goal as `failed` with a clear reason.
"""
from __future__ import annotations

from datetime import datetime, timedelta


def _make_improvement_goal(*, age_days: int = 0, target_module: str = "verifier"):
    """Build a goal in the shape meta_learner produces."""
    from backend.goals import Goal
    created = (datetime.now() - timedelta(days=age_days)).strftime(
        "%Y-%m-%d %H:%M:%S"
    )
    g = Goal(
        description=f"Improve prompt: target {target_module}",
        priority=6,
        goal_type="improvement",
        source="meta_learner_pattern",
        created=created,
        context=f"Target module guess: {target_module}",
    )
    g.add_subtask(f"Run SELF_MODIFIER.analyze_module('{target_module}')")
    g.add_subtask("Review the resulting proposal in the WebUI")
    g.add_subtask("Approve or reject explicitly")
    return g


